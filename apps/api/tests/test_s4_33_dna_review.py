DPDP = "This profile is generated by AI and is not a clinical assessment. Data processed per DPDP Act 2023."


def _make_profile(
    *,
    pid: str = "p-001",
    uid: str = "u-001",
    text: str | None = None,
    badges: list[str] | None = None,
) -> dict:
    return {
        "id": pid,
        "user_id": uid,
        "profile_text": text if text is not None else f"You are a Pattern Thinker. {DPDP}",
        "badge_labels": badges if badges is not None else ["Pattern Thinker"],
    }


# ---------------------------------------------------------------------------
# Rule: no_clinical
# ---------------------------------------------------------------------------


class TestNoClinical:
    def test_pass_no_clinical_terms(self):
        result, detail = rdp.check_no_clinical(f"You are a visual learner. {DPDP}")
        assert result == "PASS"
        assert detail == ""

    def test_fail_iq_uppercase(self):
        result, detail = rdp.check_no_clinical(f"Your IQ is high. {DPDP}")
        assert result == "FAIL"
        assert "IQ" in detail or "iq" in detail.lower()

    def test_fail_clinical_word(self):
        result, detail = rdp.check_no_clinical(f"This is a clinical assessment. {DPDP}")
        assert result == "FAIL"
        assert "clinical" in detail.lower()

    def test_fail_disorder(self):
        result, detail = rdp.check_no_clinical(f"No disorder found. {DPDP}")
        assert result == "FAIL"
        assert "disorder" in detail.lower()

    def test_fail_eq_lowercase(self):
        result, detail = rdp.check_no_clinical(f"Your eq places you here. {DPDP}")
        assert result == "FAIL"

    def test_pass_eq_in_word_is_not_flagged_wrong(self):
        # "sequence" contains "eq" but not as a whole word — should NOT be flagged
        result, _detail = rdp.check_no_clinical(f"You learn best through sequence. {DPDP}")
        assert result == "PASS"


