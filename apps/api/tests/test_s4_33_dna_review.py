class TestWriteReportCsv:
    def test_csv_has_correct_headers(self, tmp_path):
        out = str(tmp_path / "report.csv")
        rows = [{"profile_id": "p1", "user_id": "u1", "rule": "has_dpdp", "result": "PASS", "detail": ""}]
        rdp.write_report_csv(rows, out)
        with open(out, encoding="utf-8") as f:
            reader = csv.DictReader(f)
            assert set(reader.fieldnames or []) == {"profile_id", "user_id", "rule", "result", "detail"}

    def test_csv_row_count_matches_input(self, tmp_path):
        out = str(tmp_path / "report.csv")
        rows = [
            {"profile_id": f"p{i}", "user_id": "u1", "rule": "no_clinical", "result": "PASS", "detail": ""}
            for i in range(7)
        ]
        rdp.write_report_csv(rows, out)
        with open(out, encoding="utf-8") as f:
            reader = csv.DictReader(f)
            assert len(list(reader)) == 7


