class TestLoadFromFixture:
    def test_loads_10_profiles_from_sample_fixture(self):
        fixture_path = os.path.join(
            os.path.dirname(__file__), "fixtures", "sample_dna_profiles.json"
        )
        profiles = rdp.load_from_fixture(fixture_path)
        assert len(profiles) == 10

    def test_fixture_has_5_pass_profiles(self):
        fixture_path = os.path.join(
            os.path.dirname(__file__), "fixtures", "sample_dna_profiles.json"
        )
        profiles = rdp.load_from_fixture(fixture_path)
        pass_profiles = [p for p in profiles if "fail" not in p["id"]]
        assert len(pass_profiles) == 5

    def test_fixture_has_5_fail_profiles(self):
        fixture_path = os.path.join(
            os.path.dirname(__file__), "fixtures", "sample_dna_profiles.json"
        )
        profiles = rdp.load_from_fixture(fixture_path)
        fail_profiles = [p for p in profiles if "fail" in p["id"]]
        assert len(fail_profiles) == 5

    def test_missing_file_exits_2(self):
        with pytest.raises(SystemExit) as exc:
            rdp.load_from_fixture("/no/such/path/profiles.json")
        assert exc.value.code == 2

    def test_invalid_json_exits_2(self, tmp_path):
        bad = tmp_path / "bad.json"
        bad.write_text("not json", encoding="utf-8")
        with pytest.raises(SystemExit) as exc:
            rdp.load_from_fixture(str(bad))
        assert exc.value.code == 2

    def test_non_list_json_exits_2(self, tmp_path):
        bad = tmp_path / "bad.json"
        bad.write_text('{"key": "value"}', encoding="utf-8")
        with pytest.raises(SystemExit) as exc:
            rdp.load_from_fixture(str(bad))
        assert exc.value.code == 2


