# ---------------------------------------------------------------------------
# Aggregator: review_profile
# ---------------------------------------------------------------------------


class TestReviewProfile:
    def test_all_pass(self):
        profile = _make_profile()
        rows = rdp.review_profile(profile)
        assert len(rows) == 5
        assert all(r["result"] == "PASS" for r in rows)

    def test_clinical_fail_propagates(self):
        profile = _make_profile(text=f"Your IQ is high. {DPDP}", badges=["Thinker"])
        rows = rdp.review_profile(profile)
        fails = [r for r in rows if r["result"] == "FAIL"]
        assert any(r["rule"] == "no_clinical" for r in fails)

    def test_missing_dpdp_fail(self):
        profile = _make_profile(text="You are a strong learner.")
        rows = rdp.review_profile(profile)
        fails = [r for r in rows if r["result"] == "FAIL"]
        assert any(r["rule"] == "has_dpdp" for r in fails)

    def test_profile_id_and_user_id_in_rows(self):
        profile = _make_profile(pid="test-id-999", uid="user-abc")
        rows = rdp.review_profile(profile)
        assert all(r["profile_id"] == "test-id-999" for r in rows)
        assert all(r["user_id"] == "user-abc" for r in rows)


