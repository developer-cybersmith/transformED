class TestMain:
    def test_main_returns_0_all_pass(self, tmp_path):
        profiles = [_make_profile(pid=f"p{i}", uid=f"u{i}") for i in range(3)]
        fixture = tmp_path / "profiles.json"
        fixture.write_text(json.dumps(profiles), encoding="utf-8")
        out = str(tmp_path / "report.csv")
        rc = rdp.main(["--fixture", str(fixture), "--output", out])
        assert rc == 0

    def test_main_returns_1_with_fail(self, tmp_path):
        profiles = [_make_profile(pid="p1", text=f"Your IQ is high. {DPDP}")]
        fixture = tmp_path / "profiles.json"
        fixture.write_text(json.dumps(profiles), encoding="utf-8")
        out = str(tmp_path / "report.csv")
        rc = rdp.main(["--fixture", str(fixture), "--output", out])
        assert rc == 1

    def test_main_returns_2_no_input(self, monkeypatch):
        monkeypatch.delenv("SUPABASE_URL", raising=False)
        monkeypatch.delenv("SUPABASE_SERVICE_ROLE_KEY", raising=False)
        rc = rdp.main([])
        assert rc == 2

    def test_main_produces_csv_file(self, tmp_path):
        profiles = [_make_profile()]
        fixture = tmp_path / "profiles.json"
        fixture.write_text(json.dumps(profiles), encoding="utf-8")
        out = str(tmp_path / "report.csv")
        rdp.main(["--fixture", str(fixture), "--output", out])
        assert os.path.exists(out)

    def test_main_csv_has_50_rows_for_10_profiles_5_rules(self, tmp_path):
        fixture_path = os.path.join(
            os.path.dirname(__file__), "fixtures", "sample_dna_profiles.json"
        )
        out = str(tmp_path / "report.csv")
        rdp.main(["--fixture", fixture_path, "--output", out])
        with open(out, encoding="utf-8") as f:
            reader = csv.DictReader(f)
            rows = list(reader)
        assert len(rows) == 50  # 10 profiles × 5 rules

    def test_fixture_5_fail_profiles_produce_exactly_5_fail_rows(self, tmp_path):
        fixture_path = os.path.join(
            os.path.dirname(__file__), "fixtures", "sample_dna_profiles.json"
        )
        out = str(tmp_path / "report.csv")
        rdp.main(["--fixture", fixture_path, "--output", out])
        with open(out, encoding="utf-8") as f:
            reader = csv.DictReader(f)
            rows = list(reader)
        fail_rows = [r for r in rows if r["result"] == "FAIL"]
        assert len(fail_rows) == 5  # exactly one FAIL per violation profile
